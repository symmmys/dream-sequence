import { createGeometryDemoTopology } from './src/demo/geometry-demo-topology.js';
import { SliceWorldRegistry } from './src/world/slice-world-registry.js';
import { OpticalSceneRegistry } from './src/world/fields/geometry/optical-scene-registry.js';
import { createAnomalyOpticalTracer } from './src/world/fields/geometry/optical-anomaly-tracer.js';
import { createOpticalRayState } from './src/world/fields/geometry/optical-ray-integrator.js';
import { SpatialTransform } from './src/world/fields/geometry/spatial-transform.js';
import { sliceToAmbient, ambientToSlice } from './src/world/fields/geometry/spatial-4d.js';
const transform=new SpatialTransform({geometry:'euclidean',renderScale:1});
const mainWorld={terrain:{sampleAt(x,z){return {x,y:0,z}}},spatialTransform:transform,chunkSize:2000};
const d=createGeometryDemoTopology(mainWorld);
const reg=new SliceWorldRegistry();
for(const s of [d.hypercubeSlice,d.sourceSlice,d.mainSlice])reg.register(s,{spatialTransform:transform});
const sceneReg=new OpticalSceneRegistry();
const tracer=createAnomalyOpticalTracer({topology:d.topology,sliceRegistry:reg,sceneRegistry:sceneReg,chunkGraph:d.chunkGraph});
const a=d.hypercubeMainCorridor;
const end=a.source.position;
const start=sliceToAmbient(d.hypercubeSlice.frame,{x:end.x-10,y:end.y+2.5,z:end.z});
const res=tracer.trace(createOpticalRayState({position:start,momentum:{x:10,y:-2.5,z:0,w:0}}),{sliceId:d.hypercubeSlice.id,maxTransitions:1,sliceTraceOptions:{maxPathLength:20,initialStepSize:.025,maxStepSize:.05},anomalyTraceOptions:{maxPathLength:100,initialStepSize:.025,maxStepSize:.05,maxSteps:12000}});
console.log('status',res.status,'event',res.event,'context',res.context,'transition',res.transitions);
for(const p of res.pathSegments) console.log(p.kind,p.sliceId,p.anomalyId,p.result.status,p.result.event,p.result.finalState?.position,p.result.finalState?.momentum,'samples0=',p.result.samples?.[0]);
console.log('final',res.finalState);
console.log('dest local',ambientToSlice(d.mainSlice.frame,res.finalState.position));
sceneReg.dispose();reg.dispose();d.chunkGraph.dispose();
